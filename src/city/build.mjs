/* Bundles the engine into site/city/city.js and copies the decoders three.js needs.
   The /city/ page gets its own security policy (see site/_worker.js): WebAssembly is allowed there, nowhere else. */
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { KTX2Loader } from 'three/addons/loaders/KTX2Loader.js';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '../../site/city');
const prod = !process.argv.includes('--dev');
const VERSION = '7.3.0';  /* bump every release: busts the 4-hour browser cache on city files */
mkdirSync(resolve(site, 'lib/basis'), { recursive: true });
for (const f of ['basis_transcoder.js', 'basis_transcoder.wasm']) copyFileSync(resolve(here, 'node_modules/three/examples/jsm/libs/basis', f), resolve(site, 'lib/basis', f));
/* The texture decoder's worker as a real file, not a blob: the Basis transcoder builds functions from strings
   (embind), so the worker gets its own CSP with 'unsafe-eval' (see _worker.js) and the city page keeps a strict one.
   Same body three.js would put in its blob. */
{
  const fn = KTX2Loader.BasisWorker.toString();
  const body = [
    '/* Bloc City: KTX2 transcoder worker, generated by src/city/build.mjs from three.js KTX2Loader (MIT) and the Basis Universal transcoder (Apache 2.0) */',
    'let _EngineFormat = ' + JSON.stringify(KTX2Loader.EngineFormat),
    'let _EngineType = ' + JSON.stringify(KTX2Loader.EngineType),
    'let _TranscoderFormat = ' + JSON.stringify(KTX2Loader.TranscoderFormat),
    'let _BasisFormat = ' + JSON.stringify(KTX2Loader.BasisFormat),
    readFileSync(resolve(site, 'lib/basis/basis_transcoder.js'), 'utf8'),
    fn.substring(fn.indexOf('{') + 1, fn.lastIndexOf('}'))
  ].join('\n');
  writeFileSync(resolve(site, 'lib/basis/ktx2-worker.js'), body);
}

await build({
  entryPoints: { city: resolve(here, 'main.js'), plan: resolve(here, 'world/plan.worker.js') },
  outdir: site,
  bundle: true,
  format: 'esm',
  target: 'es2020',
  minify: prod,
  sourcemap: false,
  legalComments: 'eof',
  define: { 'process.env.NODE_ENV': '"production"', __V__: JSON.stringify(VERSION) },
  logLevel: 'warning'
});
console.log('built site/city/city.js and plan.js');
